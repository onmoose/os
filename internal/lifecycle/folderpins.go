package lifecycle

// Folder source pins (#604).
//
// A folder app binds a host folder into its container. The override names the
// real host path, and Docker resolves that path when the container starts, not
// when the override was written. A terminal app can swap the path for a symlink
// between two starts, so a check at install or update is not enough: the check
// and Docker's bind are two separate resolutions of the same path.
//
// The brain therefore never hands Docker the real path. Before every compose up
// and compose create it asks host-agent to walk the source without following a
// symlink and bind-mount the walked directory at a root-owned pin path under
// /run/moose/folder-pins/<dev>-<ino>. The pin is the inode: a swap after the
// walk changes the path, not the directory the pin holds. The brain writes that
// pin path into compose.pins.yml, which compose merges after the override and
// replaces by container target. The override keeps the real path, so update,
// rollback and source detection keep reading what they always read.
//
// The pin lives under /run, so a reboot clears it. The brain writes
// folder-pins.json beside the pins file; moose-folder-pins.service reads it
// before docker.service starts and mounts the pins again. Without that, Docker
// would create an empty root-owned directory at the missing pin path. That is
// safe, because it is not the real folder, but the app would serve an empty
// folder until the brain reconciled.

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/onmoose/os/internal/hostclient"
	"github.com/onmoose/os/internal/protocol"
	"github.com/onmoose/os/internal/store"
	"gopkg.in/yaml.v3"
)

const (
	folderPinsFile   = "compose.pins.yml"
	folderPinRecord  = "folder-pins.json"
	folderPinsHeader = "# Generated by moose before every compose up. Do not edit.\n"
)

// folderRefusal is a start refusal the person can act on: the folder source is
// no longer a real folder. The start job and the failed splash show its text as
// written, so it names the folder and says what to do.
type folderRefusal struct{ msg string }

func (e *folderRefusal) Error() string { return e.msg }

// folderRefusalMessage is the one sentence a swapped source gets, in the start
// job, the failed splash and the reconcile log. It names the folder and says
// what to do.
func folderRefusalMessage(appName, rel string) string {
	return fmt.Sprintf("%s cannot use the folder %q: it is not a folder any more. A file or a link is in its place. Put the folder back, then start the app again", appName, rel)
}

// readPinFailure reads the boot restorer's marker for one instance. A missing
// or unreadable marker is no marker.
func readPinFailure(dir string) (protocol.FolderPinFailure, bool) {
	b, err := os.ReadFile(filepath.Join(dir, protocol.FolderPinFailedFile))
	if err != nil {
		return protocol.FolderPinFailure{}, false
	}
	var f protocol.FolderPinFailure
	if err := json.Unmarshal(b, &f); err != nil {
		return protocol.FolderPinFailure{}, false
	}
	return f, true
}

// folderSource is one folder bind found in an instance's override.
type folderSource struct {
	src    string // the real host path as the override names it
	shared bool
	rel    string // relative to the owner's home, or to the shared root
}

// refreshFolderPins regenerates compose.pins.yml and folder-pins.json from the
// instance's current override, pinning every folder source by inode. It runs
// before every compose up and compose create. A refusal is returned as a plain
// sentence the start job and the failed splash can show.
func (m *Manager) refreshFolderPins(ctx context.Context, id, ownerUsername string) error {
	dir := m.instanceDir(id)
	raw, err := os.ReadFile(filepath.Join(dir, "compose.override.yml"))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil // nothing to bind; compose reports the missing file
		}
		return fmt.Errorf("read override: %w", err)
	}
	var ov struct {
		Services map[string]struct {
			Volumes []string `yaml:"volumes"`
		} `yaml:"services"`
	}
	if err := yaml.Unmarshal(raw, &ov); err != nil {
		return fmt.Errorf("parse override: %w", err)
	}

	inst, err := m.store.Get(id)
	if err != nil {
		return err
	}

	// Collect the distinct absolute bind sources first. A source under the
	// instance's own data dir is a private bind, not a folder source, and a
	// folderless app has only those, so it needs no owner lookup at all.
	var all []string
	seenAll := map[string]bool{}
	for _, svc := range ov.Services {
		for _, v := range svc.Volumes {
			src, _, _, ok := splitBind(v)
			if !ok || seenAll[src] {
				continue
			}
			seenAll[src] = true
			all = append(all, src)
		}
	}
	privatePrefix := m.instanceDir(id) + "/"
	needOwner := false
	for _, src := range all {
		if strings.HasPrefix(src, privatePrefix) {
			continue
		}
		if _, ok := under(src, m.sharedRoot); ok {
			continue
		}
		needOwner = true
		break
	}

	var username, home string
	if inst.Scope == store.ScopePersonal && needOwner {
		username = ownerUsername
		if username == "" {
			// A start or reconcile has only the row. The user row is the
			// authority; the record from the last pin is the fallback for a
			// test or a box whose user row is older than the pins.
			if u, err := m.store.GetUser(inst.OwnerUserID); err == nil {
				username = u.Username
			} else {
				username = readPinUsername(filepath.Join(dir, folderPinRecord))
			}
		}
		if username == "" {
			return fmt.Errorf("read the app's owner: the user row is gone and no folder pin record names the owner")
		}
		rh, err := m.host.ResolveHome(ctx, username)
		if err != nil {
			return fmt.Errorf("resolve the owner's home: %w", err)
		}
		home = rh.HomePath
	}

	// Collect the distinct folder sources, so an old host-agent can fall back
	// for all of them without pinning half an instance.
	var sources []folderSource
	for _, src := range all {
		shared, rel, isFolder := m.folderSource(src, home)
		if !isFolder {
			if strings.HasPrefix(src, privatePrefix) {
				continue // the app's own data bind, not a folder source
			}
			// The override only ever binds folder sources, under the owner's
			// home or the shared tree, and admission refuses an absolute host
			// path in the author's compose. Anything else here would be bound
			// by its real path, unpinned, so refuse it instead (fail closed).
			slog.Warn("folder pin: a bind is outside the home and the shared folders",
				"instance_id", id, "src", src)
			return &folderRefusal{msg: fmt.Sprintf("%s cannot start: one of its folders is outside your home and the shared folders. Choose its folders again", inst.Name)}
		}
		sources = append(sources, folderSource{src: src, shared: shared, rel: rel})
	}
	if len(sources) == 0 {
		clearPinFailure(dir)
		return m.writeFolderPins(dir, pinsDoc{}, nil)
	}

	pins := map[string]string{} // real source -> pin path
	records := map[string]protocol.FolderPin{}
	for _, s := range sources {
		resp, err := m.host.PinFolder(ctx, protocol.PinFolderRequest{
			Username: username, Shared: s.shared, Path: s.rel,
		})
		switch {
		case errors.Is(err, hostclient.ErrPinUnsupported):
			// The box runs an old host-agent. Keep folder apps working through
			// the prepare-folder re-check, and let the health issue say an OS
			// update closes the race.
			return m.fallbackFolderPins(ctx, dir, sources, username)
		case errors.Is(err, hostclient.ErrFolderSourceSwapped):
			return &folderRefusal{msg: folderRefusalMessage(inst.Name, s.rel)}
		case err != nil:
			return fmt.Errorf("pin folder source %q: %w", s.src, err)
		}
		pins[s.src] = resp.Path
		records[s.src] = protocol.FolderPin{Pin: resp.Path, Shared: s.shared, Username: username, Path: s.rel}
	}

	// Build the pins file service by service, replacing only the folder
	// volumes. A service with no folder volume is left out, so compose keeps
	// the override's entry for it unchanged.
	doc := pinsDoc{}
	for name, svc := range ov.Services {
		var volumes []string
		for _, v := range svc.Volumes {
			src, dest, mode, ok := splitBind(v)
			if !ok {
				continue
			}
			pin, ok := pins[src]
			if !ok {
				continue
			}
			nv := pin + ":" + dest
			if mode != "" {
				nv += ":" + mode
			}
			volumes = append(volumes, nv)
		}
		if len(volumes) > 0 {
			if doc.Services == nil {
				doc.Services = map[string]pinsService{}
			}
			doc.Services[name] = pinsService{Volumes: volumes}
		}
	}
	clearPinFailure(dir)
	return m.writeFolderPins(dir, doc, records)
}

// clearPinFailure removes the boot restorer's failure marker for an instance
// once its pins are good again.
func clearPinFailure(dir string) {
	_ = os.Remove(filepath.Join(dir, protocol.FolderPinFailedFile))
}

type pinsDoc struct {
	Services map[string]pinsService `yaml:"services,omitempty"`
}

type pinsService struct {
	Volumes []string `yaml:"volumes"`
}

// writeFolderPins writes the pins file and the record the boot restorer reads.
// Both are written atomically. doc with no services is a valid empty compose
// file, so every instance has a pins file and composeRun always merges one.
func (m *Manager) writeFolderPins(dir string, doc pinsDoc, records map[string]protocol.FolderPin) error {
	body, err := yaml.Marshal(doc)
	if err != nil {
		return fmt.Errorf("encode folder pins: %w", err)
	}
	if err := writeFileAtomic(filepath.Join(dir, folderPinsFile), append([]byte(folderPinsHeader), body...), 0o644); err != nil {
		return fmt.Errorf("write folder pins: %w", err)
	}

	rec := protocol.FolderPinRecord{Pins: []protocol.FolderPin{}}
	keys := make([]string, 0, len(records))
	for src := range records {
		keys = append(keys, src)
	}
	sort.Strings(keys)
	for _, src := range keys {
		rec.Pins = append(rec.Pins, records[src])
	}
	body, err = json.MarshalIndent(rec, "", "  ")
	if err != nil {
		return fmt.Errorf("encode folder pin record: %w", err)
	}
	body = append(body, '\n')
	if err := writeFileAtomic(filepath.Join(dir, folderPinRecord), body, 0o644); err != nil {
		return fmt.Errorf("write folder pin record: %w", err)
	}
	return nil
}

// readPinUsername returns the owner username from the last pin record, or "".
func readPinUsername(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	var rec protocol.FolderPinRecord
	if err := json.Unmarshal(b, &rec); err != nil {
		return ""
	}
	for _, p := range rec.Pins {
		if !p.Shared && p.Username != "" {
			return p.Username
		}
	}
	return ""
}

// fallbackFolderPins is the old-host-agent path. It removes the pins files and
// re-runs the check the box did at install and update: prepare-folder for a
// personal source, prepareSharedSource for a shared one. That narrows the race
// but does not close it, which is what folder-pin-unsupported tells the admin.
func (m *Manager) fallbackFolderPins(ctx context.Context, dir string, sources []folderSource, username string) error {
	_ = os.Remove(filepath.Join(dir, folderPinsFile))
	_ = os.Remove(filepath.Join(dir, folderPinRecord))

	needShared := false
	for _, s := range sources {
		needShared = needShared || s.shared
	}
	var sharedGID int
	if needShared {
		ids, err := m.host.WellKnownIdentity(ctx)
		if err != nil {
			return fmt.Errorf("read the shared identity: %w", err)
		}
		sharedGID = ids.MooseSharedGID
	}
	for _, s := range sources {
		if s.shared {
			// The shared tree is root-owned; the unprivileged dev brain cannot
			// prepare it, and shared folder apps are out of the inner loop.
			if os.Geteuid() != 0 {
				continue
			}
			if err := prepareSharedSource(m.sharedRoot, s.src, sharedGID); err != nil {
				return fmt.Errorf("prepare shared source %q: %w", s.src, err)
			}
			continue
		}
		// made_top (#658) only matters when an install asks for a new folder.
		// This re-checks a folder the app already binds, so it is not read.
		if _, err := m.host.PrepareUserFolder(ctx, username, s.rel); err != nil {
			return fmt.Errorf("prepare folder source %q: %w", s.src, err)
		}
	}
	clearPinFailure(dir)
	return nil
}

// folderSource classifies a bind source as a folder source. It is a personal
// source when it is under the owner's home, and a shared source when it is
// under the household tree. Anything else, such as the instance's own
// ./data bind, is left alone. Classifying by source, not by container target,
// also covers a Door-2 grant whose target is an arbitrary path.
func (m *Manager) folderSource(src, home string) (shared bool, rel string, ok bool) {
	if rel, ok := under(src, m.sharedRoot); ok {
		return true, rel, true
	}
	if home != "" {
		if rel, ok := under(src, home); ok {
			return false, rel, true
		}
	}
	return false, "", false
}

// under returns src relative to root when src is strictly below root.
func under(src, root string) (string, bool) {
	if root == "" || src == root || !strings.HasPrefix(src, root+"/") {
		return "", false
	}
	rel := strings.TrimPrefix(src, root+"/")
	if rel == "" || rel == ".." || strings.HasPrefix(rel, "../") || strings.Contains(rel, "/../") || strings.HasSuffix(rel, "/..") {
		return "", false
	}
	return rel, true
}

// splitBind parses a compose short-syntax bind, src:dest[:mode]. A source that
// is not an absolute path is a named volume or a relative bind, not a folder
// source. The override writes host paths as absolute paths.
func splitBind(v string) (src, dest, mode string, ok bool) {
	i := strings.LastIndex(v, ":")
	if i < 0 {
		return "", "", "", false
	}
	rest := v[:i]
	j := strings.LastIndex(rest, ":")
	if j < 0 {
		src, dest = rest, v[i+1:]
	} else {
		src, dest, mode = rest[:j], rest[j+1:], v[i+1:]
	}
	if !strings.HasPrefix(src, "/") || dest == "" {
		return "", "", "", false
	}
	return src, dest, mode, true
}
